// Differential fuzzing: random game sessions played on the TS port and on the
// native reSL oracle (pnpm oracle:build), the traces must be identical.
//
// A session starts from a fresh game (a random record level) or from a saved
// demo network (random level, year and money). The input is a mix of the
// dispatcher (tests/player.ts: routes trains, greens semaphores, calls servers)
// and random actions (clicks anywhere, building, mode and speed changes,
// pause/save, back to the main menu and loading a save again). The mix and the
// speed differ from session to session.
//
//   FUZZ_COUNT=64 FUZZ_BASE=1 pnpm fuzz
//
//   FUZZ_BASE=1019 FUZZ_COUNT=1 pnpm fuzz       one session
//   FUZZ_GEN_ONLY=1 ...                         only what the sessions go through
//
// A failing session is written to .build/fuzz-out/<name>.json with both traces
// next to it. To keep it as a golden scenario copy the JSON to
// tools/oracle/pinned and run `pnpm oracle:golden --only <name>`.
//
// A session that hangs the port (an endless loop) hangs its vitest worker: the
// run stops making progress; FUZZ_GEN_ONLY=1 finds the seed quickly.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { MemoryFileStore, createSim, type InputEvent } from '../../packages/sim/src/index';
import { DEMO_FILES, buildFiles } from '../../tools/scenario/files.mjs';
import { runScenario } from '../../tools/oracle/scenario.mjs';
import { compare, runPort } from '../golden/runner';
import { makePlayer } from '../player';

const ROOT = resolve(__dirname, '../..');
const RES = join(ROOT, 'reference/reSL/resources');
const OUT = join(ROOT, '.build/fuzz-out');
const S = 1_000_000;
const KEY = { ESC: 1, K1: 2, K2: 3, K3: 4, P: 25, S: 31, G: 34, A: 30, B: 48, SPACE: 57 };
const ME = { MOVED: 1, LP: 2, LR: 4, RP: 8, RR: 16 };

type Ev = [number, 'key' | 'mouse', ...number[]];

export interface FuzzScenario {
  name: string;
  seed: number;
  stopAtUs: number;
  dumpEveryUs: number;
  chainEveryUs: number;
  files: Record<string, unknown>;
  input: Ev[];
}

function prng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** a random session; the input is generated by playing it on the port */
export function makeScenario(seed: number): FuzzScenario {
  const rnd = prng(seed * 2654435761);
  const ri = (a: number, b: number) => a + Math.floor(rnd() * (b - a));
  const pick = <T>(xs: T[]) => xs[ri(0, xs.length)];

  const files: Record<string, unknown> = Object.fromEntries(DEMO_FILES.map((d: string) => [d, { from: d }]));
  const fromSave = rnd() < 0.7;
  const level = pick([1, 1, 2, 3, 5, 8, 12, 16, 20]);
  const demo = pick(DEMO_FILES as string[]);
  // near the end of a century now and then (the next level, U3)
  const year = rnd() < 0.35 ? ri(1985, 2000) : ri(1800, 2000);
  const money = pick([0, 20, 120, 600, 3000, 9000, 9000]);
  if (fromSave)
    files['aaaaaaaa.aa_'] = {
      from: demo,
      patch: [
        { offset: 24 + 18 + 8, u16: money },
        { offset: 24 + 36 + 8, u16: year },
        { offset: 24 + 54 + 8, u16: level },
      ],
    };
  else if (level > 1) files['results.tbl'] = { records: [{ name: 'Unknown', level }] };

  // the share of random actions: 0 (only the dispatcher) .. 1 (no dispatcher)
  const noise = pick([0, 0.03, 0.1, 0.3, 1]);
  const speed = pick([KEY.K1, KEY.K2, KEY.K3, KEY.K3]);
  const durationUs = pick([5, 10, 20, 30]) * 60 * S;
  const name = `fuzz-${seed}-${fromSave ? `${demo.slice(5)}${year}` : 'new'}-l${level}-n${Math.round(noise * 100)}`;

  const input: Ev[] = [];
  // what the session went through (to see that the fuzzer reaches the interesting places)
  const stats: Record<string, number> = {};
  const count = (k: string) => void (stats[k] = (stats[k] ?? 0) + 1);
  const sim = createSim({
    seed,
    files: new MemoryFileStore(buildFiles({ files }, RES)),
    stopAtUs: durationUs,
    onEvent: (e) => {
      if (e.type === 'trainFinished' || e.type === 'explosion' || e.type === 'save' || e.type === 'railStage') count(e.type);
      if (e.type === 'screen') count(`screen:${e.name}`);
      if (e.type === 'status' && /accident|Server|penalty|locked|money/i.test(e.text)) count(e.text.replace(/[\d,]+/g, '#'));
    },
  });
  let x = 320;
  let y = 190;
  // the events are given to the port in time order, up to the time it runs to
  let pending: Ev[] = [];
  const push = (ev: Ev) => {
    input.push(ev);
    pending.push(ev);
  };
  const advanceTo = (upTo: number) => {
    pending = pending.map((e, i) => [e, i] as const).sort((a, b) => a[0][0] - b[0][0] || a[1] - b[1]).map(([e]) => e);
    let n = 0;
    for (; n < pending.length && pending[n][0] <= upTo; ++n) {
      const [t, kind, a, b, c, d] = pending[n];
      const e: InputEvent =
        kind === 'key' ? { t, type: 'key', scancode: a, down: b !== 0 } : { t, type: 'mouse', flags: a, buttons: b, x: c, y: d };
      sim.pushInput(e);
    }
    pending = pending.slice(n);
    sim.advanceTo(upTo);
  };
  const key = (t: number, code: number) => {
    push([t, 'key', code, 1]);
    push([t + 60_000, 'key', code, 0]);
  };
  const click = (t: number, cx: number, cy: number, right = false) => {
    x = cx;
    y = cy;
    push([t, 'mouse', ME.MOVED, 0, x, y]);
    push([t + 20_000, 'mouse', right ? ME.RP : ME.LP, right ? 2 : 1, x, y]);
    push([t + 40_000 + ri(0, 150_000), 'mouse', right ? ME.RR : ME.LR, 0, x, y]);
  };

  push([1 * S, 'mouse', ME.LR, 0, 320, 175]); // the loading screen
  key(4 * S, fromSave ? KEY.A : KEY.G);
  if (fromSave) key(7 * S, KEY.G);
  key(9 * S, speed);

  const w = sim.world;
  const player = makePlayer(w);
  /** a random action at `t`; returns the time it takes */
  const randomAction = (t: number): number => {
    const r = rnd();
    if (r < 0.3) {
      // move in a few steps
      const tx = ri(0, 640);
      const ty = ri(40, 340);
      const steps = ri(1, 4);
      let dt = 0;
      for (let i = 1; i <= steps; ++i) {
        x = Math.round(x + ((tx - x) * i) / steps);
        y = Math.round(y + ((ty - y) * i) / steps);
        push([t + dt, 'mouse', ME.MOVED, 0, x, y]);
        dt += ri(10_000, 60_000);
      }
      return dt;
    }
    if (r < 0.55) {
      click(t, ri(0, 640), ri(40, 340), rnd() < 0.4);
      return 200_000;
    }
    if (r < 0.62) {
      // near the switches, semaphores and entrances
      const objs: { x: number; y: number }[] = [];
      for (let i = 0; i < w.nSwitches; ++i) objs.push(w.switches[i]);
      for (let i = 0; i < w.semaphoreCount; ++i) objs.push({ x: w.semaphores[i].pixelX, y: w.semaphores[i].pixelY - 12 });
      for (let i = 0; i < w.entranceCount; ++i) objs.push(w.entrances[i].rail);
      if (!objs.length) return 0;
      const o = pick(objs);
      click(t, Math.max(0, Math.min(639, o.x + ri(-6, 7))), Math.max(0, Math.min(349, o.y + ri(-6, 7))), rnd() < 0.3);
      return 200_000;
    }
    if (r < 0.72) {
      key(t, KEY.SPACE);
      return 100_000;
    }
    if (r < 0.75) {
      // both buttons: toggle the mouse mode
      const t2 = t + ri(5_000, 40_000);
      push([t, 'mouse', ME.LP, 1, x, y]);
      push([t2, 'mouse', ME.RP, 3, x, y]);
      push([t2 + 80_000, 'mouse', ME.LR, 2, x, y]);
      push([t2 + 100_000, 'mouse', ME.RR, 0, x, y]);
      return t2 + 120_000 - t;
    }
    if (r < 0.82) {
      key(t, pick([KEY.K1, KEY.K2, KEY.K3]));
      return 100_000;
    }
    if (r < 0.9) {
      // pause, maybe save, go on
      key(t, KEY.P);
      let dt = ri(1 * S, 3 * S);
      if (rnd() < 0.5) {
        key(t + dt, KEY.S);
        dt += ri(1 * S, 2 * S);
      }
      key(t + dt, KEY.G);
      return dt + 500_000;
    }
    if (r < 0.93) {
      // pause, bye, back from the main menu: archive (the first save) or a new game
      key(t, KEY.P);
      key(t + 1.5 * S, KEY.B);
      key(t + 6 * S, rnd() < 0.6 ? KEY.A : KEY.G);
      key(t + 9 * S, KEY.G);
      key(t + 11 * S, speed);
      return 12 * S;
    }
    if (r < 0.95) {
      key(t, KEY.ESC);
      return 200_000;
    }
    // 'G' twice: a new game from the main menu, pause + go in the game
    key(t, KEY.G);
    key(t + ri(1 * S, 2 * S), KEY.G);
    return 2.5 * S;
  };

  let busyUntil = 0;
  let haltedAt = 0;
  for (let t = 10 * S; t < durationUs - 2 * S; t += 250_000) {
    advanceTo(t);
    if (sim.halted) {
      count(`halt:${sim.halted.message}`);
      haltedAt = t;
      break;
    }
    if (t < busyUntil) continue;
    if (noise < 1) {
      let dt = 1000;
      for (const c of player.act()) {
        click(t + dt, c.x, c.y, c.right);
        dt += 220_000;
      }
      busyUntil = t + dt;
    }
    if (w.headers[3].value > (stats.maxLevel ?? 0)) stats.maxLevel = w.headers[3].value;
    if (rnd() < noise * 0.5) busyUntil = Math.max(busyUntil, t + 1000 + randomAction(t + 1000));
  }
  const stopAtUs = haltedAt ? Math.min(durationUs, haltedAt + 5 * S) : durationUs;
  // releases may overlap the next action: keep the script sorted (stable)
  const sorted = input
    .map((e, i) => [e, i] as const)
    .sort((a, b) => a[0][0] - b[0][0] || a[1] - b[1])
    .map(([e]) => e)
    .filter((e) => e[0] < stopAtUs);
  const scenario = { name, seed, stopAtUs, dumpEveryUs: 10 * S, chainEveryUs: 1 * S, files, input: sorted };
  Object.defineProperty(scenario, 'stats', { value: stats, enumerable: false });
  return scenario;
}

/** what the session went through (FUZZ_GEN_ONLY=1 shows it without running the oracle) */
export function scenarioStats(sc: FuzzScenario): Record<string, number> {
  return (sc as unknown as { stats: Record<string, number> }).stats;
}

const COUNT = Number(process.env.FUZZ_COUNT ?? 64);
const BASE = Number(process.env.FUZZ_BASE ?? 1);

/** Registers the sessions of one shard (vitest runs test files in parallel) */
export function defineFuzzShard(shard: number, shards: number): void {
  const seeds = Array.from({ length: COUNT }, (_, i) => BASE + i).filter((s) => s % shards === shard);
  describe(`fuzz against the oracle (shard ${shard + 1}/${shards})`, () => {
    if (!seeds.length) it.skip('no sessions', () => {});
    for (const seed of seeds) {
      it(`seed ${seed}`, async () => {
        const sc = makeScenario(seed);
        process.stderr.write(`${sc.name} ${(sc.stopAtUs / S / 60).toFixed(0)} min ${JSON.stringify(scenarioStats(sc))}\n`);
        if (process.env.FUZZ_KEEP) {
          // FUZZ_KEEP=1: every session goes to .build/fuzz-out (e.g. to pin one in tools/oracle/pinned)
          mkdirSync(OUT, { recursive: true });
          writeFileSync(join(OUT, `${sc.name}.json`), JSON.stringify(sc) + '\n');
        }
        if (process.env.FUZZ_GEN_ONLY) return;
        const oracle = await runScenario(sc);
        const expected = oracle.trace.split('\n');
        if (expected[expected.length - 1] === '') expected.pop();
        const actual = runPort(sc);
        let err = compare(sc.name, expected, actual.lines);
        if (!err && JSON.stringify(actual.files) !== JSON.stringify(oracle.files))
          err = `files differ\n oracle ${JSON.stringify(oracle.files)}\n port   ${JSON.stringify(actual.files)}`;
        if (err) {
          mkdirSync(OUT, { recursive: true });
          writeFileSync(join(OUT, `${sc.name}.json`), JSON.stringify(sc) + '\n');
          writeFileSync(join(OUT, `${sc.name}.expected.trace`), expected.join('\n') + '\n');
          writeFileSync(join(OUT, `${sc.name}.trace`), actual.lines.join('\n') + '\n');
        }
        expect(err, `${sc.name}: ${err}`).toBeNull();
      });
    }
  });
}
